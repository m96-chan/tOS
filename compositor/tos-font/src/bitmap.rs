//! The built-in bitmap font.
//!
//! tOS must be able to draw a readable shell before any font file exists on
//! the rootfs, so a small 5x9 face is compiled into the binary. Glyphs are
//! stored as one byte per row, bit 4 being the leftmost pixel, and are scaled
//! by an integer factor to suit the display.

use crate::glyph::{FontMetrics, Glyph, GlyphSource, RasterStyle};

/// Pixel columns in a glyph.
const GLYPH_W: u32 = 5;
/// Rows in a glyph: seven above the baseline and two below.
const GLYPH_H: u32 = 9;
/// Rows above the baseline.
const ASCENT: u32 = 7;

/// Metrics of the unscaled face.
const BASE_METRICS: FontMetrics = FontMetrics {
    cell_width: 6,
    cell_height: 11,
    baseline: 8,
    underline_position: 10,
    underline_thickness: 1,
    strikeout_position: 5,
};

