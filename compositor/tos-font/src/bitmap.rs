/// The compiled-in fallback face.
#[derive(Debug, Clone)]
pub struct BitmapFont {
    scale: u32,
}

impl Default for BitmapFont {
    fn default() -> Self {
        BitmapFont::new(1)
    }
}

impl BitmapFont {
    pub fn new(scale: u32) -> Self {
        BitmapFont {
            scale: scale.max(1),
        }
    }

    /// Pick a scale that keeps text readable on a display of this size.
    pub fn for_display(width: u32, height: u32) -> Self {
        // Aim for roughly 80 to 200 columns and at least 25 rows.
        let by_width = (width / (BASE_METRICS.cell_width * 100)).max(1);
        let by_height = (height / (BASE_METRICS.cell_height * 30)).max(1);
        BitmapFont::new(by_width.min(by_height).min(4))
    }

    pub fn scale(&self) -> u32 {
        self.scale
    }

    fn rows(c: char) -> Option<&'static [u8; GLYPH_H as usize]> {
        let cp = c as u32;
        if (0x20..0x7f).contains(&cp) {
            Some(&GLYPHS[(cp - 0x20) as usize])
        } else {
            None
        }
    }
}

impl GlyphSource for BitmapFont {
    fn metrics(&self) -> FontMetrics {
        BASE_METRICS.scaled(self.scale)
    }

    fn has_glyph(&self, c: char) -> bool {
        BitmapFont::rows(c).is_some()
    }

    fn rasterize(&mut self, c: char, style: RasterStyle) -> Option<Glyph> {
        let rows = BitmapFont::rows(c)?;
        let scale = self.scale;
        let width = GLYPH_W * scale;
        let height = GLYPH_H * scale;
        let mut coverage = vec![0u8; (width * height) as usize];

        for (row, bits) in rows.iter().enumerate() {
            for col in 0..GLYPH_W {
                // Bit 4 is the leftmost pixel.
                let on = bits & (1 << (GLYPH_W - 1 - col)) != 0;
                if !on {
                    continue;
                }
                for sy in 0..scale {
                    for sx in 0..scale {
                        let x = col * scale + sx;
                        let y = row as u32 * scale + sy;
                        coverage[(y * width + x) as usize] = 0xff;
                    }
                }
            }
        }

        let glyph = Glyph {
            width,
            height,
            left: 0,
            top: (ASCENT * scale) as i32,
            coverage,
        };

        // The bitmap face has no bold or italic cut, so both are synthesized.
        let glyph = if style.bold { glyph.embolden() } else { glyph };
        let glyph = if style.italic {
            glyph.slant(scale.max(1))
        } else {
            glyph
        };
        Some(glyph)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn art(c: char) -> String {
        let mut font = BitmapFont::new(1);
        font.rasterize(c, RasterStyle::REGULAR).unwrap().debug_art()
    }

    #[test]
    fn every_printable_ascii_has_a_glyph() {
        let font = BitmapFont::new(1);
        for cp in 0x20u32..0x7f {
            let c = char::from_u32(cp).unwrap();
            assert!(font.has_glyph(c), "missing glyph for {c:?}");
        }
        assert!(!font.has_glyph('漢'));
    }

    #[test]
    fn space_is_blank_and_others_are_not() {
        let mut font = BitmapFont::new(1);
        let space = font.rasterize(' ', RasterStyle::REGULAR).unwrap();
        assert!(space.coverage.iter().all(|&v| v == 0));
        for c in ['a', 'A', '0', '#'] {
            let g = font.rasterize(c, RasterStyle::REGULAR).unwrap();
            assert!(g.coverage.iter().any(|&v| v != 0), "{c} rendered blank");
        }
    }

    #[test]
    fn capital_a_looks_like_an_a() {
        // Reviewing the hand authored bitmaps is only possible by looking at
        // them, so the expected art is written out in full.
        assert_eq!(
            art('A'),
            concat!(
                " ### \n",
                "#   #\n",
                "#   #\n",
                "#####\n",
                "#   #\n",
                "#   #\n",
                "#   #\n",
                "     \n",
                "     \n",
            )
        );
    }

    #[test]
    fn descenders_sit_below_the_baseline() {
        // Rows 7 and 8 are below the baseline; 'g' must use them and 'o' must not.
        let mut font = BitmapFont::new(1);
        let g = font.rasterize('g', RasterStyle::REGULAR).unwrap();
        let o = font.rasterize('o', RasterStyle::REGULAR).unwrap();
        let below = |glyph: &Glyph| (7..9).any(|y| (0..5).any(|x| glyph.coverage_at(x, y) != 0));
        assert!(below(&g));
        assert!(!below(&o));
    }

    #[test]
    fn scaling_multiplies_every_dimension() {
        let mut font = BitmapFont::new(3);
        let g = font.rasterize('A', RasterStyle::REGULAR).unwrap();
        assert_eq!(g.width, GLYPH_W * 3);
        assert_eq!(g.height, GLYPH_H * 3);
        assert_eq!(font.metrics().cell_width, 18);
    }

    #[test]
    fn display_scale_keeps_a_usable_column_count() {
        let font = BitmapFont::for_display(1920, 1080);
        let cols = 1920 / font.metrics().cell_width;
        let rows = 1080 / font.metrics().cell_height;
        assert!((60..=340).contains(&cols), "unusable column count: {cols}");
        assert!(rows >= 24, "unusable row count: {rows}");
    }
}
